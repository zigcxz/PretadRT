def canonicalize_smiles(
    smi
):
    if pd.isna(
        smi
    ):
        return None

    try:
        mol = Chem.MolFromSmiles(
            str(
                smi
            )
        )

        if mol is None:
            return None

        return Chem.MolToSmiles(
            mol,
            canonical=True,
            isomericSmiles=True
        )

    except Exception:
        return None


def load_index_file(
    path
):
    if not os.path.exists(
        path
    ):
        raise FileNotFoundError(
            path
        )

    if os.path.getsize(
        path
    ) == 0:
        return np.array(
            [],
            dtype=int
        )

    return np.loadtxt(
        path,
        delimiter=",",
        ndmin=1
    ).astype(
        int
    )


def save_vector(
    path,
    arr,
    fmt=None
):
    arr = np.asarray(
        arr
    )

    if fmt is None:
        np.savetxt(
            path,
            arr,
            delimiter=","
        )

    else:
        np.savetxt(
            path,
            arr,
            delimiter=",",
            fmt=fmt
        )


def save_matrix(
    path,
    arr
):
    np.savetxt(
        path,
        np.asarray(
            arr
        ),
        delimiter=","
    )



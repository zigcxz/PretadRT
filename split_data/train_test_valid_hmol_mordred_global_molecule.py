# 6. Build Hmol + Mordred + condition for one dataset
# ============================================================

def build_features(
    dataset_id
):

    dataset_dir = os.path.join(
        TARGET_DIR,
        dataset_id
    )

    # --------------------------------------------------------
    # Reference MACCS table.
    # MACCS descriptors are NOT used here.
    # Only:
    #   column 0 = SMILES
    #   column 1 = RT
    #   row order
    # --------------------------------------------------------
    maccs_path = os.path.join(
        dataset_dir,
        f"{dataset_id}_maccs.csv"
    )

    if not os.path.exists(
        maccs_path
    ):
        raise FileNotFoundError(
            maccs_path
        )

    maccs = pd.read_csv(
        maccs_path,
        header=None
    )

    # --------------------------------------------------------
    # Mordred
    # --------------------------------------------------------
    mordred_path = os.path.join(
        dataset_dir,
        f"{dataset_id}_mordred_std.csv"
    )

    if not os.path.exists(
        mordred_path
    ):
        raise FileNotFoundError(
            mordred_path
        )

    mordred = pd.read_csv(
        mordred_path,
        header=None
    )

    if len(
        maccs
    ) != len(
        mordred
    ):
        raise RuntimeError(
            f"{dataset_id}: row number mismatch.\n"
            f"MACCS rows   = {len(maccs)}\n"
            f"Mordred rows = {len(mordred)}"
        )

    smiles_raw = (
        maccs.iloc[
            :,
            0
        ]
        .astype(str)
        .tolist()
    )

    y = (
        maccs.iloc[
            :,
            1
        ]
        .values
        .astype(
            np.float32
        )
    )

    mordred_smiles_raw = (
        mordred.iloc[
            :,
            0
        ]
        .astype(str)
        .tolist()
    )

    mordred_y = (
        mordred.iloc[
            :,
            1
        ]
        .values
        .astype(
            np.float32
        )
    )

    if not np.allclose(
        y,
        mordred_y,
        rtol=1e-6,
        atol=1e-6
    ):
        raise RuntimeError(
            f"{dataset_id}: RT mismatch between "
            "MACCS and Mordred."
        )

    canonical_smiles = np.asarray(
        [
            canonicalize_smiles(
                smi
            )
            for smi in smiles_raw
        ],
        dtype=object
    )

    mordred_canonical_smiles = np.asarray(
        [
            canonicalize_smiles(
                smi
            )
            for smi in mordred_smiles_raw
        ],
        dtype=object
    )

    for i, (
        smi1,
        smi2
    ) in enumerate(
        zip(
            canonical_smiles,
            mordred_canonical_smiles
        )
    ):

        if smi1 != smi2:
            raise RuntimeError(
                f"{dataset_id}: SMILES mismatch at row {i}\n"
                f"MACCS canonical: {smi1}\n"
                f"Mordred canonical: {smi2}"
            )

    if any(
        smi is None
        for smi in canonical_smiles
    ):
        raise RuntimeError(
            f"{dataset_id}: invalid canonical SMILES remained."
        )

    # --------------------------------------------------------
    # Hmol lookup
    # --------------------------------------------------------
    missing = [
        smi
        for smi in canonical_smiles
        if smi not in hmol_map
    ]

    if missing:
        print(
            f"[ERROR] {dataset_id}: "
            f"{len(missing)} molecules have no Hmol."
        )

        print(
            "First 10 missing:"
        )

        print(
            missing[
                :10
            ]
        )

        raise RuntimeError(
            f"{dataset_id}: Hmol coverage != 100%."
        )

    X_hmol = np.vstack(
        [
            hmol_map[
                smi
            ]
            for smi in canonical_smiles
        ]
    ).astype(
        np.float32
    )

    # --------------------------------------------------------
    # Mordred descriptors
    # column 2... = descriptor values
    # --------------------------------------------------------
    X_mordred = (
        mordred.iloc[
            :,
            2:
        ]
        .values
        .astype(
            np.float32
        )
    )

    if not np.isfinite(
        X_mordred
    ).all():
        bad = int(
            np.sum(
                ~np.isfinite(
                    X_mordred
                )
            )
        )

        raise RuntimeError(
            f"{dataset_id}: Mordred contains "
            f"{bad} NaN/Inf values."
        )

    n = len(
        y
    )

    if X_hmol.shape[
        0
    ] != n:
        raise RuntimeError(
            f"{dataset_id}: Hmol rows mismatch."
        )

    if X_mordred.shape[
        0
    ] != n:
        raise RuntimeError(
            f"{dataset_id}: Mordred rows mismatch."
        )

    # --------------------------------------------------------
    # Column
    # --------------------------------------------------------
    col_path = os.path.join(
        COL_VEC_DIR,
        f"{dataset_id}.csv"
    )

    if not os.path.exists(
        col_path
    ):
        raise FileNotFoundError(
            col_path
        )

    col = np.loadtxt(
        col_path,
        delimiter=","
    )

    col = (
        np.atleast_1d(
            col
        )
        .astype(
            np.float32
        )
        .reshape(
            -1
        )
    )

    X_col = np.tile(
        col.reshape(
            1,
            -1
        ),
        (
            n,
            1
        )
    )

    # --------------------------------------------------------
    # Gradient
    # --------------------------------------------------------
    grad_path = os.path.join(
        GRAD_VEC_DIR,
        f"{dataset_id}_gradient.csv"
    )

    if not os.path.exists(
        grad_path
    ):
        raise FileNotFoundError(
            grad_path
        )

    grad = np.loadtxt(
        grad_path,
        delimiter=","
    )

    grad = (
        np.atleast_1d(
            grad
        )
        .astype(
            np.float32
        )
        .reshape(
            -1
        )
    )

    X_grad = np.tile(
        grad.reshape(
            1,
            -1
        ),
        (
            n,
            1
        )
    )

    # --------------------------------------------------------
    # Meta
    # --------------------------------------------------------
    meta_path = os.path.join(
        META_VEC_DIR,
        f"{dataset_id}.csv"
    )

    if not os.path.exists(
        meta_path
    ):
        raise FileNotFoundError(
            meta_path
        )

    meta_df = pd.read_csv(
        meta_path
    )

    if len(
        meta_df
    ) == 0:
        raise RuntimeError(
            f"Empty meta file:\n"
            f"{meta_path}"
        )

    meta = (
        meta_df.iloc[
            0
        ]
        .values
        .astype(
            np.float32
        )
        .reshape(
            -1
        )
    )

    X_meta = np.tile(
        meta.reshape(
            1,
            -1
        ),
        (
            n,
            1
        )
    )

    # --------------------------------------------------------
    # Final continuous feature matrix
    # --------------------------------------------------------
    X = np.hstack(
        [
            X_hmol,
            X_mordred,
            X_col,
            X_grad,
            X_meta
        ]
    ).astype(
        np.float32
    )

    if not np.isfinite(
        X
    ).all():
        bad = int(
            np.sum(
                ~np.isfinite(
                    X
                )
            )
        )

        raise RuntimeError(
            f"{dataset_id}: final X contains "
            f"{bad} NaN/Inf values."
        )

    # --------------------------------------------------------
    # USP
    # --------------------------------------------------------
    usp_path = os.path.join(
        USP_DIR,
        f"{dataset_id}.txt"
    )

    if not os.path.exists(
        usp_path
    ):
        raise FileNotFoundError(
            usp_path
        )

    with open(
        usp_path,
        "r",
        encoding="utf-8"
    ) as f:

        usp = (
            f.readline()
            .strip()
        )

    if usp not in word2id:
        raise KeyError(
            f"{dataset_id}: USP '{usp}' "
            "not found in word2id."
        )

    usp_id = int(
        word2id[
            usp
        ]
    )

    usp_index = np.full(
        shape=n,
        fill_value=usp_id,
        dtype=np.int64
    )

    feature_layout = {
        "hmol_dim":
            int(
                X_hmol.shape[
                    1
                ]
            ),

        "mordred_dim":
            int(
                X_mordred.shape[
                    1
                ]
            ),

        "column_dim":
            int(
                X_col.shape[
                    1
                ]
            ),

        "gradient_dim":
            int(
                X_grad.shape[
                    1
                ]
            ),

        "meta_dim":
            int(
                X_meta.shape[
                    1
                ]
            ),

        "total_dim":
            int(
                X.shape[
                    1
                ]
            )
    }

    print(
        f"  Hmol       : {X_hmol.shape}"
    )

    print(
        f"  Mordred    : {X_mordred.shape}"
    )

    print(
        f"  Column     : {X_col.shape}"
    )

    print(
        f"  Gradient   : {X_grad.shape}"
    )

    print(
        f"  Meta       : {X_meta.shape}"
    )

    print(
        f"  Final X    : {X.shape}"
    )

    return (
        X,
        y,
        usp_index,
        canonical_smiles,
        feature_layout
    )



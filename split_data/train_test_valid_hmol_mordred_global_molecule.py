def load_global_split(
    seed
):

    path = os.path.join(
        GLOBAL_SPLIT_DIR,
        f"np_seed{seed}",
        "global_molecule_split.csv"
    )

    if not os.path.exists(
        path
    ):
        raise FileNotFoundError(
            "Global molecule split not found.\n"
            "Run train_test_valid_global_molecule.py first:\n"
            f"{path}"
        )

    split_df = pd.read_csv(
        path
    )

    required = {
        "canonical_smiles",
        "split"
    }

    missing = (
        required
        -
        set(
            split_df.columns
        )
    )

    if missing:
        raise ValueError(
            f"global_molecule_split.csv missing: {missing}"
        )

    split_df[
        "canonical_smiles"
    ] = (
        split_df[
            "canonical_smiles"
        ]
        .apply(
            canonicalize_smiles
        )
    )

    if split_df[
        "canonical_smiles"
    ].isna().any():

        raise RuntimeError(
            "Invalid molecule found in global split manifest."
        )

    train_set = set(
        split_df.loc[
            split_df[
                "split"
            ] == "train",
            "canonical_smiles"
        ]
    )

    val_set = set(
        split_df.loc[
            split_df[
                "split"
            ] == "val",
            "canonical_smiles"
        ]
    )

    test_set = set(
        split_df.loc[
            split_df[
                "split"
            ] == "test",
            "canonical_smiles"
        ]
    )

    if (
        train_set & val_set
        or
        train_set & test_set
        or
        val_set & test_set
    ):
        raise RuntimeError(
            "Global molecule split is not disjoint."
        )

    return (
        split_df,
        train_set,
        val_set,
        test_set
    )


